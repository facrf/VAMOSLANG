package transpiler

// TokenType representa o tipo de token léxico identificado.
type TokenType int

const (
	TokenEOF TokenType = iota
	TokenError
	TokenWhitespace
	TokenNewline
	TokenComment
	TokenIdentifier
	TokenKeyword
	TokenString
	TokenRawString
	TokenRune
	TokenNumber
	TokenOperator
	TokenDelimiter
)

// Token representa uma unidade léxica com sua posição no código-fonte.
type Token struct {
	Type   TokenType
	Value  string
	Line   int
	Column int
}

